def write_docx(path, blocks):
    document = docx.Document()
    for kind, value in blocks:
        if kind == 'h':
            document.add_heading(value, level=0 if value == blocks[0][1] else 1)
        elif kind == 'p':
            document.add_paragraph(value)
        else:
            table = document.add_table(rows=0, cols=len(value[0]))
            table.style = 'Table Grid'
            for row in value:
                for cell, text in zip(table.add_row().cells, row):
                    cell.text = str(text)
    document.save(path)


def write_xlsx(path, sheet_name, rows):
    workbook = Workbook()
    sheet = workbook.active
    sheet.title = sheet_name
    for row in rows:
        sheet.append(row)
    for cell in sheet[1]:
        cell.font = Font(bold=True)
    workbook.save(path)


